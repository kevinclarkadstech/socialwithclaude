import z from "zod";
import type { Mutation } from "../../../../types/mutation";
import { fail, succeed } from "../../../../utils/result";
import { notFoundError } from "../../../../error-handling";
import { logDisallowedResult } from "../../../../authorization/logDisallowedResult/logDisallowedResult";
import type { ReportReason } from "../../../posts/types/report";
import type { GetCallingUser } from "../../../users/types/calling-user";
import { canReportChatMessage } from "../../authorization/canReportChatMessage/canReportChatMessage";
import type { ChatMember } from "../../types/chat-member";
import type { ChatMessageView } from "../../types/chat-message";
import { ChatMessageReportSchema, type ChatMessageReport, type ReportedChatMessage } from "../../types/chat-message-report";

export const ReportChatMessageMutationInputSchema = ChatMessageReportSchema.pick({
    id: true,
    chatMessageId: true,
    reason: true,
    details: true,
});

export type ReportChatMessageMutationInput = z.infer<typeof ReportChatMessageMutationInputSchema>;

export const ReportChatMessageMutationOutputSchema = ChatMessageReportSchema;

export type ReportChatMessageMutationOutput = z.infer<typeof ReportChatMessageMutationOutputSchema>;

/** How many messages before the reported one the report keeps. */
export const reportedChatMessageContext = 10;

/** A message as a report keeps it: as sent, not as the reporter sees it. */
function asReported(message: ChatMessageView): ReportedChatMessage {
    const { viewer: _viewer, ...reported } = message;
    return reported;
}

/**
 * Reports a message someone else sent in one of the caller's chats, keeping
 * a snapshot of it and of the messages before it that the caller can see.
 * Reporting the same message again replaces the earlier report. `id` is
 * generated by the client.
 */
export const reportChatMessageMutation: Mutation<{ input: ReportChatMessageMutationInput, output: ReportChatMessageMutationOutput }, {
    getCallingUser: GetCallingUser;
    getChatMessageViewById: (args: { id: string; viewerId: string | null }) => Promise<ChatMessageView | null>;
    // Who's in the chat, and when the caller cleared it (earlier messages aren't theirs to report).
    getChatMembers: (args: { chatId: string }) => Promise<Pick<ChatMember, "userId" | "clearedAt">[]>;
    /** Up to `limit` messages sent before `beforeId` (and after `after`, if given), newest first. */
    getChatMessageViewsBefore: (args: {
        chatId: string;
        beforeId: string;
        after: string | null;
        viewerId: string;
        limit: number;
    }) => Promise<ChatMessageView[]>;
    createChatMessageReport: (args: {
        id: string;
        userId: string;
        chatMessageId: string;
        reason: ReportReason;
        details: string | null;
        snapshot: ChatMessageReport["snapshot"];
    }) => Promise<ChatMessageReport>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const message = await dependencies.getChatMessageViewById({ id: input.chatMessageId, viewerId: caller?.userId ?? null });
    if (!message) {
        logger.info("Message to report not found", { chatMessageId: input.chatMessageId });
        return fail(notFoundError("Message not found"));
    }

    const members = await dependencies.getChatMembers({ chatId: message.chatId });
    const allowed = canReportChatMessage({ caller, members, message });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "report-chat-message", callerId: caller?.userId, chatMessageId: message.id, chatId: message.chatId },
        });
        return allowed;
    }

    // canReportChatMessage checked the caller is a member.
    const { clearedAt } = members.find((m) => m.userId === allowed.value.userId)!;
    if (clearedAt && new Date(message.createdAt) <= new Date(clearedAt)) {
        logger.info("Message to report was cleared by the reporter", { chatMessageId: message.id });
        return fail(notFoundError("Message not found"));
    }

    const earlier = await dependencies.getChatMessageViewsBefore({
        chatId: message.chatId,
        beforeId: message.id,
        after: clearedAt,
        viewerId: allowed.value.userId,
        limit: reportedChatMessageContext,
    });
    const snapshot = { message: asReported(message), earlier: earlier.map(asReported).reverse() };
    const report = await dependencies.createChatMessageReport({ ...input, userId: allowed.value.userId, snapshot });
    return succeed(report);
};
