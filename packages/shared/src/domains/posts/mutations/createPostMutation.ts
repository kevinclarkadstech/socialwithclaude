import z from "zod";
import type { Mutation } from "../../../types/mutation";
import { fail, succeed } from "../../../utils/result";
import { authorizationError, conflictError, validationError } from "../../../error-handling";
import { requireCallerWithProfile } from "../../../logic/authorization/requireCaller";
import { logDisallowedResult } from "../../../logic/authorization/logDisallowedResult";
import type { GetCallingUser } from "../../users/types/calling-user";
import { PostSchema, type Post } from "../types/post";
import { checkPostMediaChoice, hasPostContent, placePostMedia } from "../utils/postMediaChoice";
import { maxPostPhotos } from "../constants";
import { PostMediaChoiceSchema, type PostMediaPlacement, type UploadedPostMedia } from "../types/post-media";

export const CreatePostMutationInputSchema = PostSchema.pick({ id: true, content: true }).extend({
    // Its photos in order, each uploaded and confirmed first (confirmPostMediaUploadMutation).
    media: z.array(PostMediaChoiceSchema).max(maxPostPhotos).default([]),
});

export type CreatePostMutationInput = z.infer<typeof CreatePostMutationInputSchema>;

export const CreatePostMutationOutputSchema = PostSchema;

export type CreatePostMutationOutput = z.infer<typeof CreatePostMutationOutputSchema>;

/**
 * Creates a post: text, photos or both. `id` is generated by the client;
 * retrying with it returns the post created the first time.
 */
export const createPostMutation: Mutation<{ input: CreatePostMutationInput, output: CreatePostMutationOutput }, {
    getCallingUser: GetCallingUser;
    isPostingEnabled: () => boolean;
    getPostById: (args: { id: string; viewerId: string | null }) => Promise<Post | null>;
    getPostMediaByIds: (args: { ids: string[] }) => Promise<UploadedPostMedia[]>;
    /** Creates the post and puts the photos on it. Null if the id is already used. */
    createPost: (args: { id: string; userId: string; content: string; media: PostMediaPlacement[] }) => Promise<Post | null>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const allowed = requireCallerWithProfile({ caller });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "create-post", callerId: caller?.userId },
        });
        return allowed;
    }

    if (!dependencies.isPostingEnabled()) {
        logger.info("Posting is turned off", { callerId: caller?.userId });
        return fail(authorizationError("Posting is turned off"));
    }

    if (!hasPostContent(input)) {
        return fail(validationError("Write something or add a photo"));
    }
    const found = input.media.length > 0 ? await dependencies.getPostMediaByIds({ ids: input.media.map((media) => media.id) }) : [];
    const mediaAllowed = checkPostMediaChoice({ callerId: allowed.value.userId, postId: null, chosen: input.media, found });
    if (!mediaAllowed.ok) {
        logger.warn("Post photos refused", { postId: input.id, callerId: allowed.value.userId, error: mediaAllowed.error });
        return mediaAllowed;
    }

    const createdPost = await dependencies.createPost({
        id: input.id,
        content: input.content,
        media: placePostMedia(input.media),
        userId: allowed.value.userId,
    });
    if (!createdPost) {
        const existing = await dependencies.getPostById({ id: input.id, viewerId: caller?.userId ?? null });
        if (existing && existing.createdBy === allowed.value.userId) {
            // A retry of a create that already worked.
            logger.info("Post already created", { postId: input.id, callerId: allowed.value.userId });
            return succeed(existing);
        }
        // Client ids are ULIDs, so a clash means the client reused one.
        logger.warn("Post id already used", { postId: input.id, callerId: allowed.value.userId });
        return fail(conflictError("Id is already used"));
    }

    return succeed(createdPost);
}
