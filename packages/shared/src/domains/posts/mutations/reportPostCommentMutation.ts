import z from "zod";
import type { Mutation } from "../../../types/mutation";
import { succeed } from "../../../utils/result";
import { notFound } from "../../../utils/failures";
import { canReportPostComment } from "../../../logic/authorization/posts/canReportPostComment";
import type { GetCallingUser } from "../../users/types/calling-user";
import type { PostComment } from "../types/post-comment";
import { PostCommentReportSchema, type PostCommentReport } from "../types/post-comment-report";
import type { ReportReason } from "../types/report";

export const ReportPostCommentMutationInputSchema = PostCommentReportSchema.pick({
    id: true,
    postCommentId: true,
    reason: true,
    details: true,
});

export type ReportPostCommentMutationInput = z.infer<typeof ReportPostCommentMutationInputSchema>;

export const ReportPostCommentMutationOutputSchema = PostCommentReportSchema;

export type ReportPostCommentMutationOutput = z.infer<typeof ReportPostCommentMutationOutputSchema>;

/**
 * Reports a comment, keeping a snapshot of it as it is now. Reporting the
 * same comment again replaces the earlier report. `id` is generated by the client.
 */
export const reportPostCommentMutation: Mutation<{ input: ReportPostCommentMutationInput, output: ReportPostCommentMutationOutput }, {
    getCallingUser: GetCallingUser;
    getPostCommentById: (args: { id: string }) => Promise<PostComment | null>;
    createPostCommentReport: (args: {
        id: string;
        userId: string;
        postCommentId: string;
        reason: ReportReason;
        details: string | null;
        snapshot: PostComment;
    }) => Promise<PostCommentReport>;
}> = async ({ input, dependencies }) => {
    const comment = await dependencies.getPostCommentById({ id: input.postCommentId });
    if (!comment) return notFound("Comment not found");

    const allowed = canReportPostComment(await dependencies.getCallingUser(), comment);
    if (!allowed.ok) return allowed;

    return succeed(await dependencies.createPostCommentReport({ ...input, userId: allowed.value.userId, snapshot: comment }));
}
