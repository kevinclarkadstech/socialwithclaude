import z from "zod";
import type { Mutation } from "../../../types/mutation";
import { fail, succeed } from "../../../utils/result";
import { conflictError } from "../../../error-handling";
import { requireCallerWithProfile } from "../../../logic/authorization/requireCaller";
import { logDisallowedResult } from "../../../logic/authorization/logDisallowedResult";
import type { GetCallingUser } from "../../users/types/calling-user";
import { PostSchema, PostViewSchema, type PostView } from "../types/post";
import { savedPostMedia } from "../logic/postMedia";
import { validatePostMedia } from "../validation/validatePostMedia";
import { maxPostPhotos } from "../constants";
import { PostMediaSchema, type PostMedia } from "../types/post-media";
import { ListingPriceSchema, PostListingFieldsSchema, type ListingCondition, type ListingPrice } from "../types/post-listing";

export const CreatePostListingMutationInputSchema = PostSchema.pick({ id: true, content: true })
    .extend(PostListingFieldsSchema.pick({ title: true, description: true, condition: true, isNegotiable: true }).shape)
    .extend({
        // Its photos, each uploaded first (createPostMediaUploadsMutation) under this listing's id. The server
        // sets the post, who and when, and the photos' real sizes.
        media: z.array(PostMediaSchema).max(maxPostPhotos).default([]),
    })
    .and(ListingPriceSchema);

export type CreatePostListingMutationInput = z.infer<typeof CreatePostListingMutationInputSchema>;

export const CreatePostListingMutationOutputSchema = PostViewSchema;

export type CreatePostListingMutationOutput = z.infer<typeof CreatePostListingMutationOutputSchema>;

/**
 * Creates a post and its listing details. Its photos were uploaded as they
 * were picked; they're published now, and any that can't be are left off,
 * which the app warns about. `id` is generated by the client; retrying with
 * it returns the listing created the first time.
 */
export const createPostListingMutation: Mutation<{ input: CreatePostListingMutationInput, output: CreatePostListingMutationOutput }, {
    getCallingUser: GetCallingUser;
    getPostViewById: (args: { id: string; viewerId: string | null }) => Promise<PostView | null>;
    /** Publishes the listing's uploaded photos; returns those it could, with their real dimensions. */
    publishPostPhotos: (args: { userId: string; postId: string; media: PostMedia[] }) => Promise<{ id: string; width: number; height: number }[]>;
    /** Creates the listing with its photos. Null if the id is already used. */
    createPostListing: (args: {
        id: string;
        userId: string;
        content: string;
        media: PostMedia[];
        title: string;
        description: string;
        condition: ListingCondition;
        isNegotiable: boolean;
    } & ListingPrice) => Promise<PostView | null>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const allowed = requireCallerWithProfile({ caller });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "create-post-listing", callerId: caller?.userId },
        });
        return allowed;
    }

    const userId = allowed.value.userId;
    const existing = await dependencies.getPostViewById({ id: input.id, viewerId: userId });
    if (existing) {
        if (existing.createdBy === userId) {
            // A retry of a create that already worked.
            logger.info("Listing already created", { postId: input.id, callerId: userId });
            return succeed(existing);
        }
        // Client ids are ULIDs, so a clash means the client reused one.
        logger.warn("Listing id already used", { postId: input.id, callerId: userId });
        return fail(conflictError("Id is already used"));
    }
    const valid = validatePostMedia(input);
    if (!valid.ok) {
        return valid;
    }

    const published = input.media.length > 0
        ? await dependencies.publishPostPhotos({ userId, postId: input.id, media: input.media })
        : [];
    const createdPost = await dependencies.createPostListing({
        ...input,
        media: savedPostMedia({ postId: input.id, userId, media: input.media, current: [], published }),
        userId,
    });
    if (!createdPost) {
        // Created by another request in the meantime.
        logger.warn("Listing id already used", { postId: input.id, callerId: userId });
        return fail(conflictError("Id is already used"));
    }

    return succeed(createdPost);
}
