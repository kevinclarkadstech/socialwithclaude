import z from "zod";
import type { Mutation } from "../../../../types/mutation";
import { fail, succeed } from "../../../../utils/result";
import { conflictError, notFoundError, validationError } from "../../../../error-handling";
import { canCommentOnPost } from "../../authorization/canCommentOnPost/canCommentOnPost";
import { hideUnviewablePost } from "../../utils/hideUnviewablePost/hideUnviewablePost";
import { logDisallowedResult } from "../../../../authorization/logDisallowedResult/logDisallowedResult";
import type { GetCallingUser } from "../../../users/types/calling-user";
import type { PostAccess } from "../../types/post-access";
import { PostCommentSchema, PostCommentViewSchema, type PostCommentView } from "../../types/post-comment";
import { PostCommentPhotoInputSchema, type PostCommentPhoto } from "../../types/post-comment-photo";
import { cleanUpAfterSave } from "../../utils/cleanUpAfterSave/cleanUpAfterSave";
import { excerpt } from "../../../notifications/utils/excerpt/excerpt";
import { bestEffort } from "../../../../utils/bestEffort/bestEffort";
import type { NewNotification } from "../../../notifications/types/notification";
import { commentExcerptLength } from "../../../notifications/types/notification";
import { mentionedUsernames } from "../../../notifications/utils/mentionedUsernames/mentionedUsernames";

export const CreatePostCommentMutationInputSchema = PostCommentSchema.pick({ id: true, postId: true, content: true }).extend({
    // One photo, uploaded first (createPostCommentPhotoUploadMutation). With a photo, the text can be empty.
    photo: PostCommentPhotoInputSchema.nullish(),
});

export type CreatePostCommentMutationInput = z.infer<typeof CreatePostCommentMutationInputSchema>;

export const CreatePostCommentMutationOutputSchema = PostCommentViewSchema;

export type CreatePostCommentMutationOutput = z.infer<typeof CreatePostCommentMutationOutputSchema>;

/**
 * Comments on a post, with text, a photo, or both. `id` is generated by the
 * client; retrying with it returns the comment created the first time. A
 * photo that can't be used is left out (an error if there's no text either).
 */
export const createPostCommentMutation: Mutation<{ input: CreatePostCommentMutationInput, output: CreatePostCommentMutationOutput }, {
    getCallingUser: GetCallingUser;
    /** Who can see the post (its creator, their visibility, whether the caller follows them). */
    getPostAccessById: (args: { id: string; viewerId: string | null }) => Promise<PostAccess | null>;
    getPostCommentViewById: (args: { id: string; viewerId: string | null }) => Promise<PostCommentView | null>;
    createPostComment: (args: {
        id: string;
        postId: string;
        userId: string;
        content: string;
        photo: Pick<PostCommentPhoto, "id" | "width" | "height" | "placeholder"> | null;
    }) => Promise<PostCommentView | null>;
    /** Publishes the photo uploaded for a comment; null if it isn't usable. Safe to run again. */
    publishPostCommentPhoto: (args: { userId: string; postCommentId: string; photoId: string }) => Promise<{ id: string; width: number; height: number } | null>;
    /** Deletes the uploads of a comment's photo, once the comment is saved. */
    deletePostCommentPhotoUploads: (args: { userId: string; postCommentId: string; photoIds: string[] }) => Promise<void>;
    sendNotifications: (notifications: NewNotification[]) => Promise<void>;
    /**
     * Notifies the people @-mentioned (by username) in a post or a comment on it
     * who can see the post (see mentionRecipients), except `excludedUserIds`.
     */
    notifyMentions: (args: { actorId: string; postId: string; postCommentId: string | null; usernames: string[]; excludedUserIds: string[] }) => Promise<void>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const post = await dependencies.getPostAccessById({ id: input.postId, viewerId: caller?.userId ?? null });
    if (!post) {
        logger.info("Post to comment on not found", { postId: input.postId });
        return fail(notFoundError("Post not found"));
    }

    const allowed = canCommentOnPost({ caller, post });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "create-post-comment", callerId: caller?.userId, postId: post.id },
        });
        return hideUnviewablePost({ error: allowed.error, message: "Post not found" });
    }

    const userId = allowed.value.userId;
    if (!input.content && !input.photo) {
        return fail(validationError("Write something or add a photo"));
    }
    const published = input.photo
        ? await dependencies.publishPostCommentPhoto({ userId, postCommentId: input.id, photoId: input.photo.id })
        : null;
    if (input.photo && !published && !input.content) {
        return fail(validationError("That photo couldn't be used. Try another one."));
    }
    const photo = published && input.photo ? { ...published, placeholder: input.photo.placeholder } : null;

    const comment = await dependencies.createPostComment({ id: input.id, postId: input.postId, content: input.content, userId, photo });
    if (!comment) {
        const existing = await dependencies.getPostCommentViewById({ id: input.id, viewerId: caller?.userId ?? null });
        if (existing && existing.createdBy === allowed.value.userId) {
            // A retry of a create that already worked.
            logger.info("Comment already created", { postCommentId: input.id, callerId: allowed.value.userId });
            return succeed(existing);
        }
        // Client ids are ULIDs, so a clash means the client reused one.
        logger.warn("Comment id already used", { postCommentId: input.id, callerId: allowed.value.userId });
        return fail(conflictError("Id is already used"));
    }

    // Saved: the photo's uploads aren't needed any more.
    if (input.photo) {
        const photoId = input.photo.id;
        await cleanUpAfterSave({
            logger,
            level: "warn",
            what: "comment photo upload",
            postId: input.postId,
            run: () => dependencies.deletePostCommentPhotoUploads({ userId, postCommentId: comment.id, photoIds: [photoId] }),
        });
    }

    // The post's creator is told (not when it's their own comment), and anyone mentioned in it
    // who can see the post (the creator only once, as "commented").
    const actorId = allowed.value.userId;
    const commented = post.createdBy !== actorId;
    if (commented) {
        await bestEffort({
            logger,
            what: "send a comment notification",
            run: () => dependencies.sendNotifications([{
                userId: post.createdBy,
                actorId,
                type: "commented",
                data: { postId: post.id, postCommentId: comment.id, excerpt: excerpt(comment.content, commentExcerptLength) },
            }]),
        });
    }
    const usernames = mentionedUsernames(comment.content);
    if (usernames.length > 0) {
        await bestEffort({
            logger,
            what: "send mention notifications",
            run: () => dependencies.notifyMentions({ actorId, postId: post.id, postCommentId: comment.id, usernames, excludedUserIds: commented ? [post.createdBy] : [] }),
        });
    }
    return succeed(comment);
}
