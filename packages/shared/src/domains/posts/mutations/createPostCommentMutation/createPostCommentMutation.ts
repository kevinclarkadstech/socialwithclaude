import z from "zod";
import type { Mutation } from "../../../../types/mutation";
import { fail, succeed } from "../../../../utils/result";
import { conflictError, notFoundError } from "../../../../error-handling";
import { canCommentOnPost } from "../../authorization/canCommentOnPost/canCommentOnPost";
import { logDisallowedResult } from "../../../../authorization/logDisallowedResult/logDisallowedResult";
import type { GetCallingUser } from "../../../users/types/calling-user";
import type { PostView } from "../../types/post";
import { PostCommentSchema, PostCommentViewSchema, type PostCommentView } from "../../types/post-comment";

export const CreatePostCommentMutationInputSchema = PostCommentSchema.pick({ id: true, postId: true, content: true });

export type CreatePostCommentMutationInput = z.infer<typeof CreatePostCommentMutationInputSchema>;

export const CreatePostCommentMutationOutputSchema = PostCommentViewSchema;

export type CreatePostCommentMutationOutput = z.infer<typeof CreatePostCommentMutationOutputSchema>;

/** Comments on a post. `id` is generated by the client; retrying with it returns the comment created the first time. */
export const createPostCommentMutation: Mutation<{ input: CreatePostCommentMutationInput, output: CreatePostCommentMutationOutput }, {
    getCallingUser: GetCallingUser;
    getPostViewById: (args: { id: string; viewerId: string | null }) => Promise<PostView | null>;
    getPostCommentViewById: (args: { id: string; viewerId: string | null }) => Promise<PostCommentView | null>;
    createPostComment: (args: { id: string; postId: string; userId: string; content: string }) => Promise<PostCommentView | null>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const post = await dependencies.getPostViewById({ id: input.postId, viewerId: caller?.userId ?? null });
    if (!post) {
        logger.info("Post to comment on not found", { postId: input.postId });
        return fail(notFoundError("Post not found"));
    }

    const allowed = canCommentOnPost({ caller, post });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "create-post-comment", callerId: caller?.userId, postId: post.id },
        });
        return allowed;
    }

    const comment = await dependencies.createPostComment({ ...input, userId: allowed.value.userId });
    if (!comment) {
        const existing = await dependencies.getPostCommentViewById({ id: input.id, viewerId: caller?.userId ?? null });
        if (existing && existing.createdBy === allowed.value.userId) {
            // A retry of a create that already worked.
            logger.info("Comment already created", { postCommentId: input.id, callerId: allowed.value.userId });
            return succeed(existing);
        }
        // Client ids are ULIDs, so a clash means the client reused one.
        logger.warn("Comment id already used", { postCommentId: input.id, callerId: allowed.value.userId });
        return fail(conflictError("Id is already used"));
    }

    return succeed(comment);
}
