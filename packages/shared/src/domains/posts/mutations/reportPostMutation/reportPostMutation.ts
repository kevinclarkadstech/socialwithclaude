import z from "zod";
import type { Mutation } from "../../../../types/mutation";
import { fail, succeed } from "../../../../utils/result";
import { notFoundError } from "../../../../error-handling";
import { canReportPost } from "../../authorization/canReportPost/canReportPost";
import { logDisallowedResult } from "../../../../authorization/logDisallowedResult/logDisallowedResult";
import type { GetCallingUser } from "../../../users/types/calling-user";
import { type PostView } from "../../types/post";
import { PostReportSchema, type PostReport } from "../../types/post-report";
import type { ReportReason } from "../../types/report";

export const ReportPostMutationInputSchema = PostReportSchema.pick({ id: true, postId: true, reason: true, details: true });

export type ReportPostMutationInput = z.infer<typeof ReportPostMutationInputSchema>;

export const ReportPostMutationOutputSchema = PostReportSchema;

export type ReportPostMutationOutput = z.infer<typeof ReportPostMutationOutputSchema>;

/**
 * Reports a post, keeping a snapshot of it as it is now. Reporting the same
 * post again replaces the earlier report. `id` is generated by the client.
 */
export const reportPostMutation: Mutation<{ input: ReportPostMutationInput, output: ReportPostMutationOutput }, {
    getCallingUser: GetCallingUser;
    getPostViewById: (args: { id: string; viewerId: string | null }) => Promise<PostView | null>;
    createPostReport: (args: {
        id: string;
        userId: string;
        postId: string;
        reason: ReportReason;
        details: string | null;
        snapshot: Omit<PostView, "viewer">;
    }) => Promise<PostReport>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const post = await dependencies.getPostViewById({ id: input.postId, viewerId: caller?.userId ?? null });
    if (!post) {
        logger.info("Post to report not found", { postId: input.postId });
        return fail(notFoundError("Post not found"));
    }

    const allowed = canReportPost({ caller, post });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "report-post", callerId: caller?.userId, postId: post.id },
        });
        return allowed;
    }

    // The post as created, not as the reporter sees it.
    const { viewer: _viewer, ...snapshot } = post;
    const report = await dependencies.createPostReport({ ...input, userId: allowed.value.userId, snapshot });
    return succeed(report);
}
