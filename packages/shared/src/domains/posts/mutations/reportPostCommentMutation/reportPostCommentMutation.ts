import z from "zod";
import type { Mutation } from "../../../../types/mutation";
import { fail, succeed } from "../../../../utils/result";
import { notFoundError } from "../../../../error-handling";
import { canReportPostComment } from "../../authorization/canReportPostComment/canReportPostComment";
import { logDisallowedResult } from "../../../../authorization/logDisallowedResult/logDisallowedResult";
import type { GetCallingUser } from "../../../users/types/calling-user";
import type { PostCommentView } from "../../types/post-comment";
import { PostCommentReportSchema } from "../../types/post-comment-report";
import type { ReportReason } from "../../types/report";
import { withoutSnapshot } from "../../utils/withoutSnapshot/withoutSnapshot";

export const ReportPostCommentMutationInputSchema = PostCommentReportSchema.pick({
    id: true,
    postCommentId: true,
    reason: true,
    details: true,
});

export type ReportPostCommentMutationInput = z.infer<typeof ReportPostCommentMutationInputSchema>;

/** The saved report, without its snapshot: reporting shows the reporter nothing new. */
export const ReportPostCommentMutationOutputSchema = PostCommentReportSchema.omit({ snapshot: true });

export type ReportPostCommentMutationOutput = z.infer<typeof ReportPostCommentMutationOutputSchema>;

/**
 * Reports a comment, keeping a snapshot of it as it is now. Anyone signed
 * up can, whether or not they can see its post now (canReportPostComment);
 * the snapshot is for moderators and isn't returned. Reporting the same
 * comment again replaces the earlier report. `id` is generated by the client.
 */
export const reportPostCommentMutation: Mutation<{ input: ReportPostCommentMutationInput, output: ReportPostCommentMutationOutput }, {
    getCallingUser: GetCallingUser;
    getPostCommentViewById: (args: { id: string; viewerId: string | null }) => Promise<PostCommentView | null>;
    createPostCommentReport: (args: {
        id: string;
        userId: string;
        postCommentId: string;
        reason: ReportReason;
        details: string | null;
        snapshot: Omit<PostCommentView, "viewer">;
    }) => Promise<ReportPostCommentMutationOutput>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const viewerId = caller?.userId ?? null;
    const comment = await dependencies.getPostCommentViewById({ id: input.postCommentId, viewerId });
    if (!comment) {
        logger.info("Comment to report not found", { postCommentId: input.postCommentId });
        return fail(notFoundError("Comment not found"));
    }

    const allowed = canReportPostComment({ caller });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "report-post-comment", callerId: caller?.userId, postCommentId: comment.id },
        });
        return allowed;
    }

    // The comment as created, not as the reporter sees it.
    const { viewer: _viewer, ...snapshot } = comment;
    const saved = await dependencies.createPostCommentReport({ ...input, userId: allowed.value.userId, snapshot });
    return succeed(withoutSnapshot(saved));
}
