import z from "zod";
import type { Mutation } from "../../../../types/mutation";
import { fail, succeed } from "../../../../utils/result";
import { notFoundError } from "../../../../error-handling";
import { logDisallowedResult } from "../../../../authorization/logDisallowedResult/logDisallowedResult";
import type { ReportReason } from "../../../posts/types/report";
import { canReportProfile } from "../../authorization/canReportProfile/canReportProfile";
import type { GetCallingUser } from "../../types/calling-user";
import { ProfileReportSchema, type ProfileReport } from "../../types/profile-report";
import type { UserProfile } from "../../types/user-profile";

export const ReportProfileMutationInputSchema = ProfileReportSchema.pick({
    id: true,
    reportedUserId: true,
    reason: true,
    details: true,
});

export type ReportProfileMutationInput = z.infer<typeof ReportProfileMutationInputSchema>;

export const ReportProfileMutationOutputSchema = ProfileReportSchema;

export type ReportProfileMutationOutput = z.infer<typeof ReportProfileMutationOutputSchema>;

/**
 * Reports a person, keeping a snapshot of their profile as it is now.
 * Reporting the same person again replaces the earlier report. `id` is
 * generated by the client.
 */
export const reportProfileMutation: Mutation<{ input: ReportProfileMutationInput, output: ReportProfileMutationOutput }, {
    getCallingUser: GetCallingUser;
    /** The profile whatever the blocks between the two (blocks don't stop a report). */
    getUserProfileByUserId: (args: { userId: string }) => Promise<UserProfile | null>;
    createProfileReport: (args: {
        id: string;
        userId: string;
        reportedUserId: string;
        reason: ReportReason;
        details: string | null;
        snapshot: UserProfile;
    }) => Promise<ProfileReport>;
}> = async ({ input, context: { logger }, dependencies }) => {
    const caller = await dependencies.getCallingUser();
    const target = await dependencies.getUserProfileByUserId({ userId: input.reportedUserId });
    if (!target) {
        logger.info("Profile to report not found", { reportedUserId: input.reportedUserId });
        return fail(notFoundError("Profile not found"));
    }

    const allowed = canReportProfile({ caller, target });
    if (!allowed.ok) {
        logDisallowedResult({
            logger,
            result: allowed,
            details: { action: "report-profile", callerId: caller?.userId, reportedUserId: target.userId },
        });
        return allowed;
    }

    const report = await dependencies.createProfileReport({ ...input, userId: allowed.value.userId, snapshot: target });
    return succeed(report);
};
