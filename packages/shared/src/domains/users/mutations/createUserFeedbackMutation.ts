import z from "zod";
import type { Mutation } from "../../../types/mutation";
import { succeed } from "../../../utils/result";
import { requireCallerWithProfile } from "../../../logic/authorization/requireCaller";
import type { GetCallingUser } from "../types/calling-user";
import { UserFeedbackSchema, type UserFeedback } from "../types/user-feedback";

export const CreateUserFeedbackMutationInputSchema = UserFeedbackSchema.pick({
    id: true,
    category: true,
    message: true,
    pageUrl: true,
});

export type CreateUserFeedbackMutationInput = z.infer<typeof CreateUserFeedbackMutationInputSchema>;

export const CreateUserFeedbackMutationOutputSchema = UserFeedbackSchema;

export type CreateUserFeedbackMutationOutput = z.infer<typeof CreateUserFeedbackMutationOutputSchema>;

/**
 * Sends feedback from the app. `pageUrl` is where it was sent from; the user
 * agent comes from the request. `id` is generated by the client.
 */
export const createUserFeedbackMutation: Mutation<{ input: CreateUserFeedbackMutationInput, output: CreateUserFeedbackMutationOutput }, {
    getCallingUser: GetCallingUser;
    getUserAgent: () => string | null;
    createUserFeedback: (args: Pick<UserFeedback, "id" | "userId" | "category" | "message" | "pageUrl" | "userAgent">) => Promise<UserFeedback>;
}> = async ({ input, dependencies }) => {
    const allowed = requireCallerWithProfile(await dependencies.getCallingUser());
    if (!allowed.ok) return allowed;

    return succeed(await dependencies.createUserFeedback({
        ...input,
        userId: allowed.value.userId,
        userAgent: dependencies.getUserAgent()?.slice(0, 500) ?? null,
    }));
}
