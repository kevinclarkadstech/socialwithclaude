import { z } from "zod";
import {
    PostCommentReportSchema,
    PostCommentSchema,
    PostCommentVoteSchema,
} from "@myapp/shared/domains";
import { PageInputSchema } from "@myapp/shared/common";
import { succeed } from "@myapp/shared/utils";

import {
    createPostComment,
    createPostCommentReport,
    deletePostComment,
    deletePostCommentVote,
    getPostComments,
    setPostCommentVote,
    updatePostComment,
} from "../../../data-access";
import { requireUserAndProfile } from "../context";
import { notFound } from "../errors";
import { procedure, router } from "../trpc";

const commentIdInput = z.object({ id: PostCommentSchema.shape.id });

export const postCommentsRouter = router({
    /** A post's comments, oldest first unless `order` is "newest". */
    getPostComments: procedure
        .input(PageInputSchema.extend({
            postId: PostCommentSchema.shape.postId,
            order: z.enum(["oldest", "newest"]).default("oldest"),
        }))
        .query(async ({ input }) => succeed(await getPostComments(input))),

    /** `id` is generated by the client. */
    createPostComment: procedure
        .input(PostCommentSchema.pick({ id: true, postId: true, content: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const comment = await createPostComment({ ...input, userId: user.id });
            return comment ? succeed(comment) : notFound("Post not found");
        }),

    updatePostComment: procedure
        .input(PostCommentSchema.pick({ id: true, content: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const comment = await updatePostComment({ ...input, userId: user.id });
            return comment ? succeed(comment) : notFound("Comment not found");
        }),

    deletePostComment: procedure.input(commentIdInput).mutation(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        return (await deletePostComment({ id: input.id, userId: user.id })) ? succeed() : notFound("Comment not found");
    }),

    /** Up (1) or down (-1), replacing the caller's earlier vote. */
    voteOnPostComment: procedure
        .input(PostCommentVoteSchema.pick({ postCommentId: true, value: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const vote = await setPostCommentVote({ ...input, userId: user.id });
            return vote ? succeed(vote) : notFound("Comment not found");
        }),

    /** Removes the caller's vote; succeeds if they hadn't voted. */
    deletePostCommentVote: procedure
        .input(PostCommentVoteSchema.pick({ postCommentId: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            await deletePostCommentVote({ ...input, userId: user.id });
            return succeed();
        }),

    /** Reporting the same comment again replaces the earlier report. `id` is generated by the client. */
    reportPostComment: procedure
        .input(PostCommentReportSchema.pick({ id: true, postCommentId: true, reason: true, details: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const report = await createPostCommentReport({ ...input, userId: user.id });
            return report ? succeed(report) : notFound("Comment not found");
        }),
});
