import { z } from "zod";
import { ChatMessageSchema, ChatSchema, UserProfileSchema } from "@myapp/shared/domains";
import { PageInputSchema } from "@myapp/shared/common";
import { succeed } from "@myapp/shared/utils";

import {
    clearChat,
    createChatMessage,
    createDirectChat,
    deleteChatMessage,
    getChatMember,
    getChatMessages,
    getUserChats,
    getUserProfileByUsername,
    markChatRead,
    updateChatMessage,
} from "../../../data-access";
import { requireUserAndProfile } from "../context";
import { conflict, invalid, notFound } from "../errors";
import { procedure, router } from "../trpc";

const chatIdInput = z.object({ chatId: ChatSchema.shape.id });
const messageIdInput = z.object({ id: ChatMessageSchema.shape.id });

export const chatsRouter = router({
    /**
     * The caller's chat with `username`, started with the client's `id` if
     * they don't have one yet.
     */
    getOrCreateDirectChat: procedure
        .input(ChatSchema.pick({ id: true }).extend({ username: UserProfileSchema.shape.username }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const receiver = await getUserProfileByUsername({ username: input.username });
            if (!receiver) return notFound("User not found");
            if (receiver.userId === user.id) return invalid("Cannot chat with yourself");

            const chat = await createDirectChat({ id: input.id, userId: user.id, receiverId: receiver.userId });
            return chat ? succeed(chat) : conflict("Chat id is already used");
        }),

    /** The caller's chats, newest first. */
    getMyChats: procedure.input(PageInputSchema).query(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        return succeed(await getUserChats({ userId: user.id, ...input }));
    }),

    /** A chat's messages, newest first, minus any from before the caller deleted the chat. */
    getMessages: procedure.input(chatIdInput.extend(PageInputSchema.shape)).query(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        const member = await getChatMember({ chatId: input.chatId, userId: user.id });
        if (!member) return notFound("Chat not found");
        return succeed(await getChatMessages({ ...input, after: member.clearedAt }));
    }),

    /** `id` is generated by the client. */
    sendMessage: procedure
        .input(ChatMessageSchema.pick({ id: true, chatId: true, content: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            if (!(await getChatMember({ chatId: input.chatId, userId: user.id }))) return notFound("Chat not found");
            return succeed(await createChatMessage({ ...input, userId: user.id }));
        }),

    editMessage: procedure
        .input(ChatMessageSchema.pick({ id: true, content: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const message = await updateChatMessage({ ...input, userId: user.id });
            return message ? succeed(message) : notFound("Message not found");
        }),

    /** Deletes one of the caller's messages for everyone. */
    deleteMessage: procedure.input(messageIdInput).mutation(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        return (await deleteChatMessage({ id: input.id, userId: user.id })) ? succeed() : notFound("Message not found");
    }),

    markRead: procedure.input(chatIdInput).mutation(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        const member = await markChatRead({ chatId: input.chatId, userId: user.id });
        return member ? succeed(member) : notFound("Chat not found");
    }),

    /** Deletes a chat for the caller only: its messages so far are hidden for them. */
    deleteChat: procedure.input(chatIdInput).mutation(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        const member = await clearChat({ chatId: input.chatId, userId: user.id });
        return member ? succeed(member) : notFound("Chat not found");
    }),
});
