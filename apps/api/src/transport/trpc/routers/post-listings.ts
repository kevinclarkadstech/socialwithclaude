import {
    ListingPriceSchema,
    ListingStatusSchema,
    PostListingFieldsSchema,
    PostSchema,
} from "@myapp/shared/domains";
import { PageInputSchema } from "@myapp/shared/common";
import { succeed } from "@myapp/shared/utils";

import { createPostListing, getPostListings, updatePostListing } from "../../../data-access";
import { requireUserAndProfile } from "../context";
import { notFound } from "../errors";
import { procedure, router } from "../trpc";

const listingInput = PostSchema.pick({ id: true, content: true })
    .extend(PostListingFieldsSchema.pick({ title: true, description: true, condition: true, isNegotiable: true }).shape)
    .and(ListingPriceSchema);

export const postListingsRouter = router({
    /** Listings, newest first; only those with `status` if given. */
    getListings: procedure
        .input(PageInputSchema.extend({ status: ListingStatusSchema.optional() }))
        .query(async ({ input }) => succeed(await getPostListings(input))),

    /** Creates a post and its listing details. `id` is generated by the client. */
    createListing: procedure.input(listingInput).mutation(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        return succeed(await createPostListing({ ...input, userId: user.id }));
    }),

    /** Replaces one of the caller's listings' content and details. */
    updateListing: procedure
        .input(listingInput.and(PostListingFieldsSchema.pick({ status: true })))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const post = await updatePostListing({ ...input, userId: user.id });
            return post ? succeed(post) : notFound("Listing not found");
        }),
});
