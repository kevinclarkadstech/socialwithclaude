import { z } from "zod";
import { TRPCError } from "@trpc/server";
import {
    GetFeedQueryInputSchema,
    GetPostByIdQueryInputSchema,
    PostReportSchema,
    PostSchema,
    UserProfileSchema,
    getFeedQuery,
    getPostByIdQuery,
} from "@myapp/shared/domains";
import { PageInputSchema } from "@myapp/shared/common";
import { succeed } from "@myapp/shared/utils";

import {
    createPost,
    createPostReport,
    deletePost,
    getPostById,
    getPosts,
    getUserProfileByUsername,
    updatePost,
} from "../../../data-access";
import { requireUserAndProfile } from "../context";
import { notFound } from "../errors";
import { procedure, router } from "../trpc";

const postIdInput = z.object({ id: PostSchema.shape.id });

export const postsRouter = router({
    /** Not found if it doesn't exist or was deleted. */
    getPostById: procedure.input(GetPostByIdQueryInputSchema).query(({ ctx, input }) =>
        getPostByIdQuery({
            input,
            context: { user: ctx.user, logger: ctx.logger },
            dependencies: { fetchPostById: (id) => getPostById({ id }) },
        }),
    ),

    /** Every post and listing, newest first. */
    getFeed: procedure.input(GetFeedQueryInputSchema).query(({ ctx, input }) =>
        getFeedQuery({
            input,
            context: { user: ctx.user, logger: ctx.logger },
            dependencies: { fetchPosts: (page) => getPosts(page) },
        }),
    ),

    /** A user's posts and listings, newest first. */
    getUserPosts: procedure
        .input(PageInputSchema.extend({ username: UserProfileSchema.shape.username }))
        .query(async ({ input }) => {
            const profile = await getUserProfileByUsername({ username: input.username });
            if (!profile) return notFound("User not found");
            return succeed(await getPosts({ createdBy: profile.userId, cursor: input.cursor, limit: input.limit }));
        }),

    /** `id` is generated by the client. */
    createPost: procedure
        .input(PostSchema.pick({ id: true, content: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            if (!ctx.featureFlagStore.isEnabled("usersCanPost")) {
                throw new TRPCError({ code: "FORBIDDEN", message: "POSTING_DISABLED" });
            }
            return succeed(await createPost({ ...input, userId: user.id }));
        }),

    /** Changes the content of one of the caller's posts (or listings). */
    updatePost: procedure
        .input(PostSchema.pick({ id: true, content: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const post = await updatePost({ ...input, userId: user.id });
            return post ? succeed(post) : notFound("Post not found");
        }),

    /** Deletes one of the caller's posts (or listings). */
    deletePost: procedure.input(postIdInput).mutation(async ({ ctx, input }) => {
        const { user } = await requireUserAndProfile(ctx);
        return (await deletePost({ id: input.id, userId: user.id })) ? succeed() : notFound("Post not found");
    }),

    /** Reporting the same post again replaces the earlier report. `id` is generated by the client. */
    reportPost: procedure
        .input(PostReportSchema.pick({ id: true, postId: true, reason: true, details: true }))
        .mutation(async ({ ctx, input }) => {
            const { user } = await requireUserAndProfile(ctx);
            const report = await createPostReport({ ...input, userId: user.id });
            return report ? succeed(report) : notFound("Post not found");
        }),
});
